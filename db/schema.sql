-- =====================================================================
-- Скрипт генерации базы данных fitness_db
-- Web-приложение формирования индивидуальных тренировочных программ
-- с алгоритмом адаптации рабочих весов
-- Соответствует физической модели БД (рисунок 1.7).
-- СУБД: PostgreSQL
-- =====================================================================

-- Удаление объектов (повторная инициализация).
DROP TABLE IF EXISTS personal_records  CASCADE;
DROP TABLE IF EXISTS weight_history    CASCADE;
DROP TABLE IF EXISTS workout_sets      CASCADE;
DROP TABLE IF EXISTS workouts          CASCADE;
DROP TABLE IF EXISTS program_exercises CASCADE;
DROP TABLE IF EXISTS program_days      CASCADE;
DROP TABLE IF EXISTS programs          CASCADE;
DROP TABLE IF EXISTS exercise_muscles  CASCADE;
DROP TABLE IF EXISTS exercise_media    CASCADE;
DROP TABLE IF EXISTS exercises         CASCADE;
DROP TABLE IF EXISTS muscle_groups     CASCADE;
DROP TABLE IF EXISTS backup_logs       CASCADE;
DROP TABLE IF EXISTS training_profiles CASCADE;
DROP TABLE IF EXISTS users             CASCADE;

DROP TYPE IF EXISTS user_role      CASCADE;
DROP TYPE IF EXISTS goal           CASCADE;
DROP TYPE IF EXISTS level          CASCADE;
DROP TYPE IF EXISTS program_status CASCADE;
DROP TYPE IF EXISTS decision       CASCADE;
DROP TYPE IF EXISTS record_type    CASCADE;

-- ---------------------------------------------------------------------
-- Перечислимые типы
-- ---------------------------------------------------------------------
CREATE TYPE user_role      AS ENUM ('USER', 'ADMIN');
CREATE TYPE goal           AS ENUM ('GENERAL', 'HYPERTROPHY', 'STRENGTH', 'ENDURANCE');
CREATE TYPE level          AS ENUM ('BEGINNER', 'INTERMEDIATE', 'ADVANCED');
CREATE TYPE program_status AS ENUM ('DRAFT', 'ACTIVE', 'ARCHIVED');
CREATE TYPE decision       AS ENUM ('INCREASE', 'KEEP', 'DECREASE');
CREATE TYPE record_type    AS ENUM ('MAX_WEIGHT', 'MAX_REPS', 'MAX_1RM', 'MAX_TONNAGE');

-- ---------------------------------------------------------------------
-- users – учётные записи
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         VARCHAR(50)  NOT NULL,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          user_role    NOT NULL DEFAULT 'USER',
    is_blocked    BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_logins SMALLINT     NOT NULL DEFAULT 0,
    locked_until  TIMESTAMP,                                         -- временная блокировка входа
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_login_ak UNIQUE (login),                       -- AK1
    CONSTRAINT users_email_ak UNIQUE (email),                       -- AK2
    CONSTRAINT users_failed_logins_chk CHECK (failed_logins >= 0)
);

-- ---------------------------------------------------------------------
-- training_profiles – тренировочный профиль (связь 1 : 0..1 с users,
-- композиция: удаляется вместе с пользователем)
-- ---------------------------------------------------------------------
CREATE TABLE training_profiles (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            INTEGER NOT NULL,
    goal               goal,
    level              level,
    workouts_per_week  SMALLINT,
    equipment          TEXT[]  NOT NULL DEFAULT '{}',
    body_weight        NUMERIC(5,2),
    CONSTRAINT training_profiles_user_ak UNIQUE (user_id),          -- AK1
    CONSTRAINT training_profiles_user_fk FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT training_profiles_wpw_chk CHECK (workouts_per_week BETWEEN 1 AND 7),
    CONSTRAINT training_profiles_bw_chk  CHECK (body_weight > 0)
);

-- ---------------------------------------------------------------------
-- backup_logs – журнал резервного копирования
-- ---------------------------------------------------------------------
CREATE TABLE backup_logs (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   INTEGER      NOT NULL,
    file_name  VARCHAR(255) NOT NULL,
    type       VARCHAR(10)  NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status     VARCHAR(10)  NOT NULL,
    CONSTRAINT backup_logs_admin_fk FOREIGN KEY (admin_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- muscle_groups – группы мышц (рекурсивная связь «антагонист» 0..1 : 0..1)
-- ---------------------------------------------------------------------
CREATE TABLE muscle_groups (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL,
    antagonist_id INTEGER,
    CONSTRAINT muscle_groups_name_ak       UNIQUE (name),           -- AK1
    CONSTRAINT muscle_groups_antagonist_ak UNIQUE (antagonist_id),  -- AK2
    CONSTRAINT muscle_groups_antagonist_fk FOREIGN KEY (antagonist_id)
        REFERENCES muscle_groups (id) ON DELETE SET NULL,
    CONSTRAINT muscle_groups_self_chk CHECK (antagonist_id <> id)
);

-- ---------------------------------------------------------------------
-- exercises – справочник упражнений
-- ---------------------------------------------------------------------
CREATE TABLE exercises (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    primary_muscle_id INTEGER      NOT NULL,
    equipment         VARCHAR(20)  NOT NULL,
    difficulty        SMALLINT     NOT NULL,
    technique         TEXT,
    weight_step       NUMERIC(4,2) NOT NULL,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT exercises_name_ak UNIQUE (name),                     -- AK1
    CONSTRAINT exercises_primary_muscle_fk FOREIGN KEY (primary_muscle_id)
        REFERENCES muscle_groups (id) ON DELETE RESTRICT,
    CONSTRAINT exercises_weight_step_chk CHECK (weight_step >= 0)
);

-- ---------------------------------------------------------------------
-- exercise_media – медиафайлы упражнения (композиция с exercises)
-- ---------------------------------------------------------------------
CREATE TABLE exercise_media (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id INTEGER     NOT NULL,
    media_type  VARCHAR(10) NOT NULL,
    mime_type   VARCHAR(50) NOT NULL,
    data        BYTEA       NOT NULL,
    CONSTRAINT exercise_media_exercise_fk FOREIGN KEY (exercise_id)
        REFERENCES exercises (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- exercise_muscles – вспомогательные группы мышц упражнения
-- (зависимая сущность, идентифицирующие связи)
-- ---------------------------------------------------------------------
CREATE TABLE exercise_muscles (
    exercise_id     INTEGER NOT NULL,
    muscle_group_id INTEGER NOT NULL,
    CONSTRAINT exercise_muscles_pk PRIMARY KEY (exercise_id, muscle_group_id),
    CONSTRAINT exercise_muscles_exercise_fk FOREIGN KEY (exercise_id)
        REFERENCES exercises (id) ON DELETE CASCADE,
    CONSTRAINT exercise_muscles_muscle_fk FOREIGN KEY (muscle_group_id)
        REFERENCES muscle_groups (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- programs – тренировочные программы (личные и шаблонные).
-- owner_id допускает NULL: у шаблонной программы владельца нет.
-- ---------------------------------------------------------------------
CREATE TABLE programs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    INTEGER,
    title       VARCHAR(100)   NOT NULL,
    goal        goal           NOT NULL,
    level       level          NOT NULL,
    is_template BOOLEAN        NOT NULL DEFAULT FALSE,
    status      program_status NOT NULL DEFAULT 'DRAFT',
    created_at  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT programs_owner_fk FOREIGN KEY (owner_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT programs_owner_template_chk CHECK (
        (is_template AND owner_id IS NULL) OR (NOT is_template AND owner_id IS NOT NULL)
    )
);

-- У пользователя может быть не более одной активной программы.
CREATE UNIQUE INDEX programs_one_active_idx
    ON programs (owner_id) WHERE status = 'ACTIVE' AND NOT is_template;

-- ---------------------------------------------------------------------
-- program_days – тренировочные дни программы (композиция с programs)
-- ---------------------------------------------------------------------
CREATE TABLE program_days (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id INTEGER      NOT NULL,
    day_number SMALLINT     NOT NULL,
    title      VARCHAR(100) NOT NULL,
    CONSTRAINT program_days_number_ak UNIQUE (program_id, day_number), -- AK1
    CONSTRAINT program_days_program_fk FOREIGN KEY (program_id)
        REFERENCES programs (id) ON DELETE CASCADE,
    CONSTRAINT program_days_number_chk CHECK (day_number >= 1)
);

-- ---------------------------------------------------------------------
-- program_exercises – упражнения тренировочного дня с параметрами нагрузки
-- (композиция с program_days)
-- ---------------------------------------------------------------------
CREATE TABLE program_exercises (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_day_id INTEGER      NOT NULL,
    exercise_id    INTEGER      NOT NULL,
    order_no       SMALLINT     NOT NULL,
    sets           SMALLINT     NOT NULL,
    reps_min       SMALLINT     NOT NULL,
    reps_max       SMALLINT     NOT NULL,
    rest_sec       SMALLINT     NOT NULL,
    working_weight NUMERIC(6,2) NOT NULL DEFAULT 0,
    CONSTRAINT program_exercises_day_fk FOREIGN KEY (program_day_id)
        REFERENCES program_days (id) ON DELETE CASCADE,
    CONSTRAINT program_exercises_exercise_fk FOREIGN KEY (exercise_id)
        REFERENCES exercises (id) ON DELETE RESTRICT,
    CONSTRAINT program_exercises_sets_chk   CHECK (sets > 0),
    CONSTRAINT program_exercises_reps_chk   CHECK (reps_min > 0 AND reps_min <= reps_max),
    CONSTRAINT program_exercises_rest_chk   CHECK (rest_sec >= 0),
    CONSTRAINT program_exercises_weight_chk CHECK (working_weight >= 0)
);

-- ---------------------------------------------------------------------
-- workouts – выполненные тренировки
-- ---------------------------------------------------------------------
CREATE TABLE workouts (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER       NOT NULL,
    program_day_id INTEGER       NOT NULL,
    date           DATE          NOT NULL DEFAULT CURRENT_DATE,
    tonnage        NUMERIC(10,2) NOT NULL DEFAULT 0,
    is_completed   BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT workouts_user_fk FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT workouts_program_day_fk FOREIGN KEY (program_day_id)
        REFERENCES program_days (id) ON DELETE RESTRICT,
    CONSTRAINT workouts_tonnage_chk CHECK (tonnage >= 0)
);

-- ---------------------------------------------------------------------
-- workout_sets – подходы тренировки (композиция с workouts)
-- ---------------------------------------------------------------------
CREATE TABLE workout_sets (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id          INTEGER      NOT NULL,
    program_exercise_id INTEGER      NOT NULL,
    set_no              SMALLINT     NOT NULL,
    weight              NUMERIC(6,2) NOT NULL,
    reps                SMALLINT     NOT NULL,
    CONSTRAINT workout_sets_workout_fk FOREIGN KEY (workout_id)
        REFERENCES workouts (id) ON DELETE CASCADE,
    CONSTRAINT workout_sets_program_exercise_fk FOREIGN KEY (program_exercise_id)
        REFERENCES program_exercises (id) ON DELETE RESTRICT,
    CONSTRAINT workout_sets_set_no_chk CHECK (set_no >= 1),
    CONSTRAINT workout_sets_weight_chk CHECK (weight >= 0),
    CONSTRAINT workout_sets_reps_chk   CHECK (reps BETWEEN 1 AND 50)
);

-- ---------------------------------------------------------------------
-- weight_history – история изменения рабочего веса
-- (композиция с program_exercises)
-- ---------------------------------------------------------------------
CREATE TABLE weight_history (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_exercise_id INTEGER      NOT NULL,
    date                DATE         NOT NULL DEFAULT CURRENT_DATE,
    old_weight          NUMERIC(6,2) NOT NULL,
    new_weight          NUMERIC(6,2) NOT NULL,
    decision            decision     NOT NULL,
    CONSTRAINT weight_history_program_exercise_fk FOREIGN KEY (program_exercise_id)
        REFERENCES program_exercises (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- personal_records – личные рекорды
-- ---------------------------------------------------------------------
CREATE TABLE personal_records (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER       NOT NULL,
    exercise_id INTEGER       NOT NULL,
    type        record_type   NOT NULL,
    value       NUMERIC(10,2) NOT NULL,
    achieved_at DATE          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT personal_records_user_fk FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT personal_records_exercise_fk FOREIGN KEY (exercise_id)
        REFERENCES exercises (id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- Индексы по внешним ключам и частым условиям выборки
-- ---------------------------------------------------------------------
CREATE INDEX exercises_primary_muscle_idx      ON exercises (primary_muscle_id);
CREATE INDEX exercise_media_exercise_idx       ON exercise_media (exercise_id);
CREATE INDEX exercise_muscles_muscle_idx       ON exercise_muscles (muscle_group_id);
CREATE INDEX programs_owner_idx                ON programs (owner_id);
CREATE INDEX program_exercises_day_idx         ON program_exercises (program_day_id);
CREATE INDEX workouts_user_date_idx            ON workouts (user_id, date);
CREATE INDEX workout_sets_workout_idx          ON workout_sets (workout_id);
CREATE INDEX workout_sets_program_exercise_idx ON workout_sets (program_exercise_id);
CREATE INDEX weight_history_pe_idx             ON weight_history (program_exercise_id);
CREATE INDEX personal_records_user_ex_idx      ON personal_records (user_id, exercise_id);
CREATE INDEX backup_logs_admin_idx             ON backup_logs (admin_id);
