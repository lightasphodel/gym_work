-- ---------------------------------------------------------------------
-- Шаблонная программа «Full Body для начинающих»:
-- 3 дня, 3 подхода по 8–12 повторений, отдых 90 с (цель GENERAL, таблица 1.1).
-- Рабочий вес 0 — пользователь задаёт его после копирования шаблона.
-- Статус ACTIVE у шаблона означает «опубликован»: пользователи видят и копируют его.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_program_id INTEGER;
    v_day_id     INTEGER;
    v_added      INTEGER;
    d            RECORD;
BEGIN
    IF EXISTS (SELECT 1 FROM programs WHERE is_template AND title = 'Full Body для начинающих') THEN
        RETURN;
    END IF;

    INSERT INTO programs (owner_id, title, goal, level, is_template, status)
    VALUES (NULL, 'Full Body для начинающих', 'GENERAL', 'BEGINNER', TRUE, 'ACTIVE')
    RETURNING id INTO v_program_id;

    FOR d IN
        SELECT * FROM (VALUES
            (1, 'Full Body A', ARRAY['Приседания со штангой', 'Жим штанги лёжа',
                                     'Тяга верхнего блока к груди', 'Жим гантелей сидя',
                                     'Скручивания на полу']),
            (2, 'Full Body B', ARRAY['Румынская тяга со штангой', 'Жим гантелей на наклонной скамье',
                                     'Тяга гантели одной рукой в наклоне', 'Махи гантелями в стороны',
                                     'Подъём штанги на бицепс']),
            (3, 'Full Body C', ARRAY['Жим ногами в тренажёре', 'Жим от груди в тренажёре',
                                     'Тяга штанги в наклоне', 'Разгибание рук на блоке',
                                     'Подъёмы на носки в тренажёре стоя'])
        ) AS t (day_number, title, exercises)
    LOOP
        INSERT INTO program_days (program_id, day_number, title)
        VALUES (v_program_id, d.day_number, d.title)
        RETURNING id INTO v_day_id;

        INSERT INTO program_exercises
            (program_day_id, exercise_id, order_no, sets, reps_min, reps_max, rest_sec, working_weight)
        SELECT v_day_id, e.id, x.ord, 3, 8, 12, 90, 0
          FROM unnest(d.exercises) WITH ORDINALITY AS x (name, ord)
          JOIN exercises e ON e.name = x.name;

        GET DIAGNOSTICS v_added = ROW_COUNT;
        IF v_added <> cardinality(d.exercises) THEN
            RAISE EXCEPTION 'Шаблон «%»: не найдены упражнения дня %', 'Full Body для начинающих', d.day_number;
        END IF;
    END LOOP;
END
$$;

